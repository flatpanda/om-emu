#!/usr/bin/env node
// gen_vsc_regs --check: render the VSC register-offset header from the firmware's own name tables
// (src/dev/vscregs.mjs readTable) and compare it with the committed fixture
// checks/fixtures/om1-vsc-regs.h (check_display group 13 and test_dev compare it too). Without --check it exits 2: the
// fixture is compared, never rewritten. --header PATH compares with another file (the negative control).
//   node emu/checks/gen_vsc_regs.mjs --check [--image PATH] [--header PATH]
import fs from 'node:fs';
import path from 'node:path';
import { FIXTURES, ORIGINAL, runMain, readBytes, SystemExit } from './lib/env.mjs';
import { parseArgs } from './lib/args.mjs';
import { readTable, TABLES } from '../src/dev/vscregs.mjs';

const HEADER = path.join(FIXTURES, 'om1-vsc-regs.h');
const hx = (v, w) => v.toString(16).padStart(w, '0');

export function render(image) {
  const t = { chan: readTable(image, ...TABLES.chan), out: readTable(image, ...TABLES.out) };
  const lines = [
    '/* GENERATED by emu/checks/gen_vsc_regs.mjs from the E143 v1.9 main block; do not edit.',
    " * Register offsets accepted by the om1-vsc model = the firmware's own VSC",
    ' * name tables: body 0x331da0 (per channel, 503) and 0x332d60 (output block',
    ' * 0x9BB98000, 115). Entry {u32 name pointer, u32 word index}. */',
    '#ifndef HW_MN10300_OM1_VSC_REGS_H', '#define HW_MN10300_OM1_VSC_REGS_H', '',
    'typedef struct OM1VscRegName {', '    uint16_t offset;', '    const char *name;',
    '} OM1VscRegName;', ''];
  for (const [key, label] of [['chan', 'CHAN'], ['out', 'OUT']]) {
    lines.push(`#define OM1_VSC_${label}_REG_COUNT ${t[key].length}`);
    lines.push(`static const OM1VscRegName om1_vsc_${key}_regs[OM1_VSC_${label}_REG_COUNT] = {`);
    for (const [offset, name] of t[key]) lines.push(`    { 0x${hx(offset, 3)}, "${name}" },`);
    lines.push('};');
    lines.push('');
  }
  lines.push('#endif');
  return lines.join('\n') + '\n';
}

function main(argv) {
  const a = parseArgs('gen_vsc_regs.mjs', argv, [{ opt: '--image', type: 'path' }, { opt: '--check', type: 'flag' }, { opt: '--header', type: 'path' }]);
  const image = a.image ?? ORIGINAL, header = a.header ? path.resolve(a.header) : HEADER;
  const text = render(readBytes(image));
  if (!a.check) a.error('without --check there is nothing to do: the header is a committed fixture, compared and never rewritten');
  if (fs.readFileSync(header, 'utf8') !== text) throw new SystemExit(`${header} differs from the tables in ${image}`);
  console.log(`${path.basename(header)} matches the image tables`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) runMain('gen_vsc_regs.mjs', main);
